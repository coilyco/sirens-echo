// applyFeatureFlags reads every flag into cfg. An unparsable value is named and
// fatal rather than silently taking the default, unlike a knob.
func applyFeatureFlags(cfg *Config, lookup func(string) string) error {
	for _, flag := range featureFlags(cfg) {
		value, err := boolOrDefault(lookup(flag.env), flag.fallback)
		if err != nil {
			return fmt.Errorf("%s: %w", flag.env, err)
		}
		*flag.target = value
	}
	return nil
}

// RenderFlagReference writes the generated reference of every feature a
// deployment may turn on or off.
func RenderFlagReference() string {
	var reference Config
	rows := make([]string, 0, len(featureFlags(&reference)))
	for _, flag := range featureFlags(&reference) {
		rows = append(rows, fmt.Sprintf(
			"%-34s %-5s %s",
			strings.TrimPrefix(flag.env, "SIRENS_ECHO_"),
			boolWord(flag.fallback),
			flag.summary,
		))
	}
	sort.Strings(rows)
	return FlagReferenceHeading + "\n" +
		"Generated by `just flags`, every name prefixed SIRENS_ECHO_. The second column\n" +
		"is the default, and an unparsable value is fatal at startup rather than ignored.\n" +
		"Why the switches live where they do: docs/sirens-echo-tuning.md\n\n" +
		"NAME                               ON?   WHAT IT TURNS ON\n" +
		strings.Join(rows, "\n") + "\n"
}

func boolWord(on bool) string {
	if on {
		return "on"
	}
	return "off"
}
