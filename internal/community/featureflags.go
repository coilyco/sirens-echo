// Every enabled/disabled switch this service ships lives here, for the reason
// the numbers live in config.go. See docs/sirens-echo-tuning.md.

// FlagReferenceHeading opens the generated reference, so the writer and the
// checker cannot disagree about the first line.
const FlagReferenceHeading = "Every feature a deployment may turn on or off."

// featureFlag binds one switch, its environment name, its default, and what it
// turns on. One line each, so none of the four can drift from the others.
type featureFlag struct {
	env      string
	target   *bool
	fallback bool
	// summary is what the flag turns on, in one sentence for the reference.
	summary string
}

